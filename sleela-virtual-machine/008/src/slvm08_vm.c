/* ==========================================================================
 * slvm08_vm.c  --  SLVM/8 "Executive" runnable virtual machine.
 *
 * A REAL virtual machine: it links the shared native SLeeLa Core engine
 * (impl/core, archived as libslcore.a) and runs a compiled .sleela program
 * artifact on it. SLVM/8's distinguishing contribution --
 *   supervised execution: admission, leases, transactions, audit
 * -- is expressed in SOURCE here: the admission step builds a well-formed
 * instance of this grade's own feature and calls this grade's real validator,
 * and (under --selfcheck) proves a malformed instance is REJECTED. A program
 * only runs on this VM once that grade-specific contract is admitted. This is
 * what distinguishes grade 8 from the other grades at the source level.
 *
 * Usage:
 *   slvm-08 <program.sleela-artifact>   run a compiled artifact on SLVM/8
 *   slvm-08 --selfcheck                 exercise the grade's validator only
 *
 * Core public API: impl/core/sleela_core.h. Build: this directory's Makefile
 * links ../../impl/build/libslcore.a and this grade's feature source(s).
 *
 * Generated by sleela-virtual-machine/tools/gen-premium-vm-runners.py.
 * Copyright (c) Max Rupplin - MEARVK LLC - 2026
 * ========================================================================== */
#include "sleela_core.h"
#include "slvm8.h"
#include "slvm8_admission.h"
#include <stdio.h>
#include <string.h>

static const char* SLVM_CODENAME = "Executive";
static const char* SLVM_FEATURE  = "supervised execution: admission, leases, transactions, audit";

/* Admit a well-formed instance of this grade's feature. Returns 0 if this
 * grade's real validator ACCEPTS the well-formed instance, -1 otherwise.
 * Named slvm08_vm_admit (not slvm08_admit) to avoid clashing with any
 * grade feature API that already defines an admit entry point. */
static int slvm08_vm_admit(void) {

    slvm8_admission_t a = { 1,1,1,1,1,1,1, 0 };
    int rc0 = slvm8_admission_evaluate(&a);
    if (rc0 == 0) rc0 = slvm8_admission_validate(&a);
    return (rc0 == 0) ? 0 : -1;
}

/* Prove the grade's validator is real: a deliberately malformed instance must
 * be REJECTED. Returns 0 if the bad instance is correctly rejected. */
static int slvm08_vm_reject(void) {

    slvm8_admission_t deny = { 1,0,1,1,1,1,1, 0 };  /* policy_valid cleared */
    int rc1 = slvm8_admission_evaluate(&deny);
    return (rc1 != 0) ? 0 : -1;
}

static int slvm08_run_artifact(const char* path) {
    if (!slvm_is_artifact_file(path)) {
        fprintf(stderr, "slvm-08: not a compiled .sleela artifact: %s\n", path);
        return 2;
    }
    SLVM* vm = slvm_load_file(path);
    if (!vm) { fprintf(stderr, "slvm-08: failed to load artifact: %s\n", path); return 1; }
    SLResult r = slvm_run(vm);
    if (r == SLR_ERROR) {
        const char* e = slvm_error(vm);
        fprintf(stderr, "slvm-08: runtime error: %s\n", e ? e : "(unknown)");
        slvm_free(vm);
        return 1;
    }
    slvm_free(vm);
    return 0;
}

int main(int argc, char** argv) {
    if (argc >= 2 && strcmp(argv[1], "--selfcheck") == 0) {
        if (slvm08_vm_admit() != 0) {
            fprintf(stderr, "slvm-08: %s admission FAILED (valid instance rejected)\n", SLVM_CODENAME);
            return 1;
        }
        if (slvm08_vm_reject() != 0) {
            fprintf(stderr, "slvm-08: %s validator is not discriminating (bad instance admitted)\n", SLVM_CODENAME);
            return 1;
        }
        printf("slvm-08: %s VM self-check PASS "
               "(Core engine linked; grade validator admits valid + rejects invalid: %s)\n",
               SLVM_CODENAME, SLVM_FEATURE);
        return 0;
    }
    if (argc < 2) {
        fprintf(stderr, "usage: slvm-08 <program.sleela-artifact> | --selfcheck\n");
        return 2;
    }
    if (slvm08_vm_admit() != 0) {
        fprintf(stderr, "slvm-08: %s admission failed; boot denied\n", SLVM_CODENAME);
        return 1;
    }
    return slvm08_run_artifact(argv[1]);
}
