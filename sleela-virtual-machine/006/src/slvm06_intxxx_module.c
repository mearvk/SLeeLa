#include "slvm06_intxxx_module.h"

static int slvm06_is_power_of_two(uint32_t w) {
    return w != 0u && (w & (w - 1u)) == 0u;
}

int slvm06_intxxx_is_series_width(uint32_t w) {
    if (!slvm06_is_power_of_two(w)) return 0;
    if (w < SLVM06_INTXXX_MIN_WIDTH) return 0;
    if (w > SLVM06_INTXXX_MAX_WIDTH) return 0;
    return 1;
}

slvm06_intxxx_slot_t slvm06_intxxx_slot_for_width(uint32_t w) {
    if (!slvm06_intxxx_is_series_width(w)) return SLVM06_SLOT_NONE;
    return (w <= SLVM06_INTXXX_NATIVE_NARROW) ? SLVM06_SLOT_INT : SLVM06_SLOT_INT128;
}

uint32_t slvm06_intxxx_count_series_widths(void) {
    uint32_t count = 0u;
    uint32_t w;
    for (w = SLVM06_INTXXX_MIN_WIDTH; w <= SLVM06_INTXXX_MAX_WIDTH; w <<= 1) {
        if (slvm06_intxxx_is_series_width(w)) count++;
    }
    return count;
}

int slvm06_intxxx_module_validate(const slvm06_intxxx_module_t* m) {
    if (m == 0) return -1;
    if (m->min_width    != SLVM06_INTXXX_MIN_WIDTH)     return -1;
    if (m->max_width    != SLVM06_INTXXX_MAX_WIDTH)     return -1;
    if (m->narrow_width != SLVM06_INTXXX_NATIVE_NARROW) return -1;
    if (m->series_count != SLVM06_INTXXX_SERIES_COUNT)  return -1;
    if (!m->has_signed && !m->has_unsigned)              return -1;
    if (slvm06_intxxx_count_series_widths() != m->series_count) return -1;
    if (slvm06_intxxx_slot_for_width(32u)       != SLVM06_SLOT_INT)    return -1;
    if (slvm06_intxxx_slot_for_width(64u)       != SLVM06_SLOT_INT)    return -1;
    if (slvm06_intxxx_slot_for_width(128u)      != SLVM06_SLOT_INT128) return -1;
    if (slvm06_intxxx_slot_for_width(16777216u) != SLVM06_SLOT_INT128) return -1;
    if (slvm06_intxxx_slot_for_width(16u)       != SLVM06_SLOT_NONE)   return -1; /* below floor  */
    if (slvm06_intxxx_slot_for_width(48u)       != SLVM06_SLOT_NONE)   return -1; /* not pow2      */
    if (slvm06_intxxx_slot_for_width(33554432u) != SLVM06_SLOT_NONE)   return -1; /* above ceiling */
    return 0;
}

int slvm06_intxxx_module_is_full_series(const slvm06_intxxx_module_t* m) {
    if (m == 0) return 0;
    return (m->has_signed && m->has_unsigned &&
            m->min_width    == SLVM06_INTXXX_MIN_WIDTH &&
            m->max_width    == SLVM06_INTXXX_MAX_WIDTH &&
            m->series_count == SLVM06_INTXXX_SERIES_COUNT) ? 1 : 0;
}
