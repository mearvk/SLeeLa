std::string SourceEmitter::language_name(SourceLanguage l) {
    switch (l) { case SourceLanguage::Java: return "java"; case SourceLanguage::Sleela: return "sleela";
        case SourceLanguage::C: return "c"; case SourceLanguage::CPlusPlus: return "c++"; }
    return "unknown";
}
std::string SourceEmitter::extension(SourceLanguage l) {
    switch (l) { case SourceLanguage::Java: return ".java"; case SourceLanguage::Sleela: return ".sleela";
        case SourceLanguage::C: return ".c"; case SourceLanguage::CPlusPlus: return ".cpp"; }
    return ".txt";
}
std::string SourceEmitter::header_extension(SourceLanguage l) {
    switch (l) { case SourceLanguage::C: return ".h"; case SourceLanguage::CPlusPlus: return ".hpp";
        case SourceLanguage::Java: return ".java"; case SourceLanguage::Sleela: return ".sleela"; }
    return ".h";
}
std::string SourceEmitter::emit(const Artifact& a, const std::vector<Instruction>& ins,
                                const ControlFlowGraph& cfg, const std::vector<Symbol>& funcs,
                                const DecompilationOptions& options) {
    (void)cfg;
    switch (options.language) {
        case SourceLanguage::Java: return emit_java(a, ins, funcs, options);
        case SourceLanguage::Sleela: return emit_sleela(a, ins, funcs, options);
        case SourceLanguage::C: return emit_c_like(a, ins, funcs, options, false);
        case SourceLanguage::CPlusPlus: return emit_c_like(a, ins, funcs, options, true);
    }
    throw std::invalid_argument("unsupported source output language");
}
std::string SourceEmitter::emit(const Artifact& a, const std::vector<Instruction>& ins,
                                const ControlFlowGraph& cfg, const std::vector<Symbol>& funcs,
                                const Module& module, const DecompilationOptions& options) {
    (void)cfg;
    switch (options.language) {
        case SourceLanguage::Java: return emit_java(a, ins, funcs, options, &module);
        case SourceLanguage::Sleela: return emit_sleela(a, ins, funcs, options, &module);
        case SourceLanguage::C: return emit_c_like(a, ins, funcs, options, false, &module);
        case SourceLanguage::CPlusPlus: return emit_c_like(a, ins, funcs, options, true, &module);
    }
    throw std::invalid_argument("unsupported source output language");
}
std::string SourceEmitter::emit_header(const Artifact& a, const std::vector<Symbol>& funcs,
                                       const DecompilationOptions& options) {
    switch (options.language) {
        case SourceLanguage::C: return emit_c_header(a, funcs, options, false);
        case SourceLanguage::CPlusPlus: return emit_c_header(a, funcs, options, true);
        case SourceLanguage::Java: { std::vector<Instruction> none; return emit_java(a, none, funcs, options); }
        case SourceLanguage::Sleela: { std::vector<Instruction> none; return emit_sleela(a, none, funcs, options); }
    }
    throw std::invalid_argument("unsupported header output language");
}
