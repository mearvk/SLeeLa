#!/usr/bin/env python3
"""Implement the java.* Throwable hierarchy in SLeeLa source.

Turns the JDK 28 envelopes for every java.* exception and error under
lib/java/java/ into real SLeeLa classes:

  * the Java superclass is declared with `extends` (resolved OOD inheritance,
    syntax 1.10+), using the documented JDK 28 class hierarchy below;
  * java.lang.Throwable carries the real state and behavior (detail message,
    cause, suppressed list, stack-trace slot, toString, printStackTrace ...);
  * every subclass declares its documented constructor and any class-specific
    fields/accessors (ParseException.getErrorOffset, URISyntaxException,
    FileSystemException.getFile, SQLException.getSQLState, ...).

Idempotent: the generated member block is delimited by BEGIN/END markers and
regenerated in place; the metadata block and envelope helpers are preserved.

Constraints of the current compiler that shape the output (to be revisited in
the keyword/semantics pass):
  * one constructor per class (no overload resolution) -- each class gets the
    most representative Java constructor;
  * no implicit subtype assignability -- callers upcast explicitly, e.g.
    t.initCause((Throwable) ioe);
  * `super(...)` calls are not lowered -- constructors assign inherited
    fields directly;
  * method dispatch is static (no virtual override through a base-typed
    receiver or an implicit-this call), so subclasses never override
    getMessage(): every derived message is composed into detailMessage at
    construction (or when a setter changes an input);
  * base-class field initializers do not run for subclass instances, so
    every constructor first initializes the whole inherited state (root
    first, see INIT); reference fields are set to null explicitly (an
    uninitialized String field reads as "").

Usage (from the repository root):
    python3 lib/java/tools/jdk28_implement_throwables.py [--check]
"""
