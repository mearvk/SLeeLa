def key_for(simple: str, near: str) -> str:
    """Resolve a superclass simple name to its PARENT key (prefer same package)."""
    cands = [k for k in list(PARENT) + ["lang/Throwable"] if k.rsplit("/", 1)[-1] == simple]
    if not cands:
        raise SystemExit(f"unknown superclass {simple}")
    pkg = near.rsplit("/", 1)[0]
    for c in cands:
        if c.rsplit("/", 1)[0] == pkg:
            return c
    lang = [c for c in cands if c.startswith("lang/")]
    return (lang or cands)[0]


def chain_init(key: str) -> str:
    chain = []
    k = key
    while True:
        chain.append(k)
        if k == "lang/Throwable":
            break
        k = key_for(PARENT[k], k)
    stmts = " ".join(INIT[c] for c in reversed(chain) if c in INIT)
    # Qualify with this. so a constructor parameter of the same name is not hit.
    return re.sub(r"(^|; )(\w+) = ", lambda mo: mo.group(1) + "this." + mo.group(2) + " = ", stmts)


