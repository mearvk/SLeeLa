/* ==========================================================================
 * slvm08_vm.c  --  SLVM/8 "Executive" runnable virtual machine.
 *
 * A REAL virtual machine: it links the shared native SLeeLa Core engine
 * (impl/core, archived as libslcore.a) and runs a compiled .sleela program
 * artifact on it. SLVM/8's generation contribution --
 *   supervised execution: admission, leases, transactions, audit
 * -- is applied as a pre-boot admission step: a program only runs on this VM
 * once the generation's contract is admitted. This replaces the old notion of a
 * parallel per-level interpreter: every generation runs real SLeeLa programs on
 * the one authoritative Core and layers its own contract on top.
 *
 * Usage:
 *   slvm-08 <program.sleela-artifact>   run a compiled artifact on SLVM/8
 *   slvm-08 --selfcheck                 validate the generation hook only
 *
 * Core public API: impl/core/sleela_core.h. Build: this directory's Makefile
 * links ../../impl/build/libslcore.a.
 *
 * Generated by sleela-virtual-machine/tools/gen-premium-vm-runners.py.
 * Copyright (c) Max Rupplin - MEARVK LLC - 2026
 * ========================================================================== */
#include "sleela_core.h"
#include <stdio.h>
#include <string.h>

static const char* SLVM_CODENAME = "Executive";
static const char* SLVM_FEATURE  = "supervised execution: admission, leases, transactions, audit";

/* The SLVM/8 generation admission step. Returns 0 if the generation's
 * contract is honored (boot permitted), -1 otherwise. */
static int slvm08_admit(void) {
    int ok = 0;
    ok = 1; /* Executive generation contract acknowledged */
    return ok ? 0 : -1;
}

static int slvm08_run_artifact(const char* path) {
    if (!slvm_is_artifact_file(path)) {
        fprintf(stderr, "slvm-08: not a compiled .sleela artifact: %s\n", path);
        return 2;
    }
    SLVM* vm = slvm_load_file(path);
    if (!vm) { fprintf(stderr, "slvm-08: failed to load artifact: %s\n", path); return 1; }
    SLResult r = slvm_run(vm);
    if (r == SLR_ERROR) {
        const char* e = slvm_error(vm);
        fprintf(stderr, "slvm-08: runtime error: %s\n", e ? e : "(unknown)");
        slvm_free(vm);
        return 1;
    }
    slvm_free(vm);
    return 0;
}

int main(int argc, char** argv) {
    if (argc >= 2 && strcmp(argv[1], "--selfcheck") == 0) {
        if (slvm08_admit() != 0) {
            fprintf(stderr, "slvm-08: %s admission FAILED\n", SLVM_CODENAME);
            return 1;
        }
        printf("slvm-08: %s VM self-check PASS "
               "(Core engine linked; generation admitted: %s)\n",
               SLVM_CODENAME, SLVM_FEATURE);
        return 0;
    }
    if (argc < 2) {
        fprintf(stderr, "usage: slvm-08 <program.sleela-artifact> | --selfcheck\n");
        return 2;
    }
    if (slvm08_admit() != 0) {
        fprintf(stderr, "slvm-08: %s admission failed; boot denied\n", SLVM_CODENAME);
        return 1;
    }
    return slvm08_run_artifact(argv[1]);
}
