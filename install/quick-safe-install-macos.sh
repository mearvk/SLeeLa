#!/usr/bin/env bash
set -euo pipefail
SCRIPT_DIR="$(cd -- "$(dirname -- "\${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd -- "$SCRIPT_DIR/.." && pwd)"
DESTINATION=""
NO_BUILD=0
SKIP_OPTIONAL=0
SCOPE=""
usage() {
  cat <<'USAGE'
SLeeLa macOS installer
  ./install/quick-safe-install-macos.sh [--user|--system] [--destination PATH] [--no-build] [--skip-optional-products]
USAGE
}
while (($#)); do
  case "$1" in
    --user) SCOPE=user ;;
    --system) SCOPE=system ;;
    --destination) shift; (($#)) || { echo "--destination needs a path" >&2; exit 2; }; DESTINATION="$1" ;;
    --no-build) NO_BUILD=1 ;;
    --skip-optional-products) SKIP_OPTIONAL=1 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown option: $1" >&2; usage >&2; exit 2 ;;
  esac
  shift
done
if [[ -z "$SCOPE" ]]; then
  printf 'Installation scope:\n  1) User-local (recommended; no administrator access)\n  2) System-wide (/usr/local; administrator approval required)\n'
  read -r -p 'Choose scope (1|2) [1]: ' answer
  case "\${answer:-1}" in 1) SCOPE=user ;; 2) SCOPE=system ;; *) echo "Choose 1 or 2." >&2; exit 2 ;; esac
fi
if [[ -z "$DESTINATION" ]]; then
  if [[ "$SCOPE" == user ]]; then DESTINATION="\${SLEELA_INSTALL_ROOT:-$HOME/.local/sleela}"
  else DESTINATION="\${SLEELA_SYSTEM_ROOT:-/usr/local/lib/sleela}"; fi
fi
if [[ "$SCOPE" == system && "$DESTINATION" != /usr/local/* && "$DESTINATION" != /opt/* ]]; then
  echo "Refusing a system install destination outside /usr/local or /opt: $DESTINATION" >&2; exit 2
fi
if [[ "$SCOPE" == system ]] && ! command -v sudo >/dev/null 2>&1; then
  echo "System install requires sudo; use --user for a user-local install." >&2; exit 1
fi
command -v python3 >/dev/null 2>&1 || { echo "Python 3 is required." >&2; exit 127; }
command -v make >/dev/null 2>&1 || { echo "make is required; install Xcode Command Line Tools." >&2; exit 127; }
if (( NO_BUILD == 0 )); then
  echo "Building native macOS products and selected smoke tests..."
  /bin/sh "$REPO_ROOT/build/native-macos.sh"
fi
STAGE="$(mktemp -d "\${TMPDIR:-/tmp}/sleela-macos-install.XXXXXX")"
cleanup() { rm -rf "$STAGE"; }
trap cleanup EXIT
mkdir -p "$STAGE/lib" "$STAGE/bin" "$STAGE/config" "$STAGE/tools" "$STAGE/security"
if [[ -d "$REPO_ROOT/lib" ]]; then ditto "$REPO_ROOT/lib" "$STAGE/lib"; fi
cp "$REPO_ROOT/tools/verify-before-execution.py" "$STAGE/tools/"
cp "$REPO_ROOT/security/sha256-manifest.json" "$STAGE/security/"
python3 - "$REPO_ROOT" "$STAGE" <<'PY_MANIFEST_COPY'
import json, os, shutil, sys
repo, stage = map(os.path.abspath, sys.argv[1:3])
manifest = os.path.join(repo, "security", "sha256-manifest.json")
with open(manifest, encoding="utf-8") as stream:
    entries = json.load(stream).get("files", [])
for entry in entries:
    rel = entry["path"]
    src = os.path.abspath(os.path.join(repo, rel))
    if os.path.commonpath((repo, src)) != repo or not os.path.isfile(src):
        raise SystemExit("Invalid or missing manifest source: " + rel)
    dst = os.path.join(stage, rel)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    shutil.copy2(src, dst)
PY_MANIFEST_COPY
products=(sleela)
if (( SKIP_OPTIONAL == 0 )); then products+=(sleelvac nordshrift); fi
for product in "\${products[@]}"; do
  built="$REPO_ROOT/impl/build/$product"
  [[ -f "$built" && -x "$built" ]] || { echo "Required compiled product missing or not executable: $built" >&2; exit 1; }
  install -m 755 "$built" "$STAGE/bin/$product"
done
cat > "$STAGE/config/startup.conf" <<EOF
# Generated by SLeeLa macOS installer
install.mode=$SCOPE
install.root=$DESTINATION
EOF
if [[ "$SCOPE" == user ]]; then
  if [[ -e "$DESTINATION" ]]; then
    backup_root="$HOME/Library/Application Support/SLeeLa-backups"
    mkdir -p "$backup_root"
    backup="$backup_root/$(date +%Y%m%d-%H%M%S)-$(uuidgen | tr '[:upper:]' '[:lower:]')"
    ditto "$DESTINATION" "$backup"
    echo "Backup: $backup"
  fi
  mkdir -p "$(dirname "$DESTINATION")"
  ditto "$STAGE" "$DESTINATION"
  bin_dir="$DESTINATION/bin"
  case ":$PATH:" in *":$bin_dir:"*) ;; *)
    profile="$HOME/.zprofile"
    touch "$profile"
    if ! grep -Fq "$bin_dir" "$profile"; then
      printf '\n# SLeeLa\nexport PATH="%s:$PATH"\nexport SLEELA_HOME="%s"\n' "$bin_dir" "$DESTINATION" >> "$profile"
    fi
    echo "Added $bin_dir to ~/.zprofile (open a new terminal)."
    ;;
  esac
else
  backup_root="/usr/local/var/backups/sleela"
  if [[ -e "$DESTINATION" ]]; then
    backup="$backup_root/$(date +%Y%m%d-%H%M%S)-$(uuidgen | tr '[:upper:]' '[:lower:]')"
    sudo mkdir -p "$backup_root"
    sudo ditto "$DESTINATION" "$backup"
    echo "Backup: $backup"
  fi
  sudo mkdir -p "$DESTINATION" /usr/local/bin
  sudo ditto "$STAGE" "$DESTINATION"
  for product in "\${products[@]}"; do sudo ln -sfn "$DESTINATION/bin/$product" "/usr/local/bin/$product"; done
fi
echo "SLeeLa macOS installation complete."
echo "Install root: $DESTINATION"
echo "Configuration: $DESTINATION/config/startup.conf"
