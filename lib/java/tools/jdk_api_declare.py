#!/usr/bin/env python3
"""Generate the mechanically-complete part of the JDK API in /lib/java.

Reads lib/java/api/jdk-api.jsonl (the reflected public JDK API, written by
tools/ApiDump.java) and, for every public type, writes a declarations block

    < ---- BEGIN java declarations (generated by tools/jdk_api_declare.py) ---- >
    ...
    < ---- END java declarations ---- >

holding exactly the parts of the type whose Java meaning is fully determined
by the API itself, with no behavior to invent:

  * constants -- public/protected static final fields of primitive or String
    type, with their real values read from the JDK;
  * fields -- the remaining public/protected fields (declared with their Java
    names; instance fields start at the SLeeLa default);
  * abstract methods -- every abstract method of an interface, abstract class
    or annotation type, declared with its Java name and SLeeLa-mapped
    signature. Calling one throws java.lang.AbstractMethodError, which is
    what the JVM does for an abstract method without an implementation;
  * enum types -- complete: one static final instance per constant (identity
    preserved), name, ordinal, toString, values, valueOf (with the Java
    IllegalArgumentException / NullPointerException), compareTo, equals,
    hashCode;
  * record types -- complete: canonical constructor, component accessors,
    and the Java record equals / hashCode / toString.

Types that are missing from the tree get a file (from the JDK 28 index
envelope under early_access when one exists). Types that already carry a
hand-written `BEGIN java implementation` block only receive the constants
and fields they do not already declare.

Signature mapping: int/short/byte/char -> int, long -> long, float/double ->
double, boolean -> boolean, String -> String, primitive arrays -> int[] /
long[] / double[] / boolean[], String[] -> String[], other reference arrays
-> Any[], everything else -> Any (generic erasure; also keeps unrelated
classes from being loaded). Members whose Java name is a SLeeLa reserved word
(print, record, native, ...) or collides with the envelope helpers are not
declared (and so stay uncovered in the coverage report).

Idempotent. usage: python3 lib/java/tools/jdk_api_declare.py [--check]
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
API = ROOT / "api" / "jdk-api.jsonl"
DOCS = ROOT / "early_access" / "jdk28" / "docs" / "api"
BEGIN = "  < ---- BEGIN java declarations (generated by tools/jdk_api_declare.py) ---- >"
END = "  < ---- END java declarations ---- >"
IMPL_BEGIN = "< ---- BEGIN java implementation"
MAX_FIELDS = 64

RESERVED = set("""abstract boolean break case catch class const continue default do double else enum
extends false final finally for if implements import instanceof int int128 int64 interface long
native new non-sealed null package print private protected public record require return sealed
static strictfp String struct super switch synchronized this throw throws transient true try
usualgc usualmem accuratemem void volatile while yield gc mem ran material authorial author Any
close""".split())
ENVELOPE = {"typeName", "available", "construct", "invoke", "invokeStatic", "javaType",
            "getMetaVersion", "setMetaVersion", "getMetaId", "setMetaId", "getAuthor", "setAuthor",
            "getDate", "setDate", "getCopyright", "setCopyright", "getTrademark", "setTrademark",
            "getCorporation", "setCorporation", "getOrigin", "setOrigin", "getBirthDate",
            "setBirthDate", "getScienceRating", "setScienceRating", "getNationalSchedule",
            "setNationalSchedule"}

PRIM = {"int": "int", "short": "int", "byte": "int", "char": "int", "long": "long",
        "float": "double", "double": "double", "boolean": "boolean", "void": "void",
        "java.lang.String": "String"}
PRIM_ARRAY = {"int[]": "int[]", "short[]": "int[]", "byte[]": "int[]", "char[]": "int[]",
              "long[]": "long[]", "float[]": "double[]", "double[]": "double[]",
              "boolean[]": "boolean[]", "java.lang.String[]": "String[]"}


def sl_type(t: str) -> str:
    if t in PRIM:
        return PRIM[t]
    if t in PRIM_ARRAY:
        return PRIM_ARRAY[t]
    if t.endswith("[]") and not t.endswith("[][]"):
        return "Any[]"
    return "Any"


def default_value(t: str) -> str:
    return {"int": "0", "long": "0", "double": "0.0", "boolean": "false"}.get(t, "null")


def literal(java_type: str, raw) -> str | None:
    """SLeeLa literal for a reflected constant value, or None when not representable."""
    t = sl_type(java_type)
    if t == "String":
        s = raw
        if any(ord(c) < 32 or ord(c) > 126 for c in s):
            return None
        return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if t == "boolean":
        return "true" if str(raw) == "true" else "false"
    if t in ("int", "long"):
        v = int(raw)
        if v == -9223372036854775808:
            return "-9223372036854775807 - 1"
        return str(v)
    if t == "double":
        s = str(raw)
        if s in ("NaN", "Infinity", "-Infinity"):
            return None
        if raw and 0 < abs(float(s)) < 2.2250738585072014e-308:
            return None  # subnormal literals are rejected by the lexer
        if "E" not in s and "." not in s:
            s += ".0"
        return s
    return None


def type_file(name: str, binary: str) -> Path:
    outer = binary.split("$", 1)[0]
    pkg = outer.rsplit(".", 1)[0]
    simple = name[len(pkg) + 1:]
    return ROOT.joinpath(*pkg.split("."), simple + ".sleela")


def docs_envelope(t) -> Path | None:
    outer = t["binary"].split("$", 1)[0]
    pkg = outer.rsplit(".", 1)[0]
    simple = t["name"][len(pkg) + 1:]
    p = DOCS / t["module"] / Path(*pkg.split(".")) / (simple + ".sleela")
    return p if p.is_file() else None


def new_file_text(t) -> str:
    """Envelope text for a type that has no file yet."""
    outer = t["binary"].split("$", 1)[0]
    pkg = outer.rsplit(".", 1)[0]
    simple = t["name"][len(pkg) + 1:]
    cls = simple.split(".")[-1]
    rel = "lib/java/" + "/".join(pkg.split(".")) + "/" + simple + ".sleela"
    meta_id = 0
    env = docs_envelope(t)
    if env:
        m = re.search(r"int metaId = (\d+);", env.read_text(encoding="utf-8", errors="replace"))
        if m:
            meta_id = int(m.group(1))
    nested = ""
    if "." in simple:
        nested = ("\n   This is a nested Java type; the file keeps the binary name. Nested types\n"
                  "   are not yet resolved by the library loader (see JDK28-PROCEDURAL-IMPLEMENTATION.md).")
    return f'''<< {rel}
   SLeeLa Java SE/JDK 28 source envelope.
   Definition: Native SLeeLa source declaration for the Java type {t["name"]}.

   The Java class name is retained exactly. The SLeeLa declaration is the source
   contract; Java behavior is supplied only through the conformance boundary.{nested} >>
#sleela 2.5
material;

class {cls} {{
  < ---- Descriptive metadata (version 1.11 nested-friendly accessors) ---- >
  << Eleven catalogued attributes with getter/setter pairs, so a GUI, loader,
     or catalog can read and (where appropriate) override this record.
     Values are faithful to the subject's real origin where publicly known. >>
  String metaVersion = "1.0.0";
  int metaId = {meta_id};
  String metaAuthor = "Oracle / OpenJDK";
  String metaDate = "2026-11-10";
  String metaCopyright = "GPLv2 with Classpath Exception (OpenJDK)";
  String metaTrademark = "Java";
  String metaCorporation = "Oracle Corporation";
  < metaOrigin: National | <nation> | International | Galactic >
  String metaOrigin = "International";
  String metaBirthDate = "2026-11-10";
  < metaScienceRating: maturity/robustness on a 1..10 scale >
  int metaScienceRating = 9;
  < metaNationalSchedule: a real, citable instrument or "none" >
  String metaNationalSchedule = "OpenJDK (JDK 28 API)";

  String getMetaVersion() {{ return metaVersion; }}
  void setMetaVersion(String v) {{ metaVersion = v; }}
  int getMetaId() {{ return metaId; }}
  void setMetaId(int v) {{ metaId = v; }}
  String getAuthor() {{ return metaAuthor; }}
  void setAuthor(String v) {{ metaAuthor = v; }}
  String getDate() {{ return metaDate; }}
  void setDate(String v) {{ metaDate = v; }}
  String getCopyright() {{ return metaCopyright; }}
  void setCopyright(String v) {{ metaCopyright = v; }}
  String getTrademark() {{ return metaTrademark; }}
  void setTrademark(String v) {{ metaTrademark = v; }}
  String getCorporation() {{ return metaCorporation; }}
  void setCorporation(String v) {{ metaCorporation = v; }}
  String getOrigin() {{ return metaOrigin; }}
  void setOrigin(String v) {{ metaOrigin = v; }}
  String getBirthDate() {{ return metaBirthDate; }}
  void setBirthDate(String v) {{ metaBirthDate = v; }}
  int getScienceRating() {{ return metaScienceRating; }}
  void setScienceRating(int v) {{ metaScienceRating = v; }}
  String getNationalSchedule() {{ return metaNationalSchedule; }}
  void setNationalSchedule(String v) {{ metaNationalSchedule = v; }}
  String javaType = "{t["name"]}";
  String typeName() {{ return javaType; }}
  boolean available() {{ return javaType != ""; }}
  String construct() {{ return "java.construct:" + javaType; }}
  String invoke(String operation) {{ return "java.invoke:" + javaType + ":" + operation; }}
  String invokeStatic(String operation) {{ return "java.static:" + javaType + ":" + operation; }}
}}
'''


FIELD_DECL = re.compile(r"^  (?:static )?(?:final )?[A-Za-z_][\w\[\]]* +(\w+)\s*(?:=|;)", re.M)
METHOD_DECL = re.compile(r"^  (?:static )?[A-Za-z_][\w\[\]]* +(\w+)\s*\(", re.M)


def usable(name: str, cls: str) -> bool:
    return name not in RESERVED and name not in ENVELOPE and name != cls and re.fullmatch(r"[A-Za-z_]\w*", name) is not None


def declarations(t, cls: str, existing_fields: set, existing_methods: set, instance_fields: int, has_impl: bool):
    fq = t["name"]
    out = []
    taken = set(existing_fields) | set(existing_methods)
    consts, insts = [], []
    for f in t["fields"]:
        name, jtype, is_static = f[0], f[1], f[2]
        if not usable(name, cls) or name in taken:
            continue
        st = sl_type(jtype)
        if is_static and len(f) > 3:
            lit = literal(jtype, f[3])
            if lit is None:
                continue
            consts.append(f"  static final {st} {name} = {lit};")
            taken.add(name)
        elif is_static:
            consts.append(f"  static {st} {name} = {default_value(st)};")
            taken.add(name)
        else:
            if instance_fields >= MAX_FIELDS - 1:
                continue
            insts.append(f"  {st} {name};")
            instance_fields += 1
            taken.add(name)
    if consts:
        out.append("  < constants and static fields (values reflected from the JDK) >")
        out += consts
    if insts:
        out.append("  < public and protected instance fields >")
        out += insts
    kind = t["kind"]
    if kind == "enum" and not has_impl:
        out += enum_members(t, cls, taken)
    elif kind == "record" and not has_impl:
        out += record_members(t, cls, taken)
    if not has_impl:
        stubs = []
        # Overloads that erase to the same SLeeLa signature are declared once.
        seen_sigs = set()
        for m in t["methods"]:
            name, ret, params, is_static, is_abstract = m[0], m[1], m[2], m[3], m[4]
            if name == "<init>" or not is_abstract or not usable(name, cls) or name in existing_fields:
                continue
            if name in taken and name not in {s[0] for s in stubs}:
                continue
            key = (name, tuple(sl_type(p) for p in params))
            if key in seen_sigs:
                continue
            seen_sigs.add(key)
            ps = ", ".join(f"{sl_type(p)} p{i}" for i, p in enumerate(params))
            sig = f"{fq}.{name}(" + ",".join(p.rsplit(".", 1)[-1] for p in params) + ")"
            stubs.append((name, f'  {sl_type(ret)} {name}({ps}) {{ throw new AbstractMethodError("{sig}"); }}'))
            taken.add(name)
        if stubs:
            out.append("  < abstract methods: implemented by a concrete subtype; a direct call throws AbstractMethodError as on the JVM >")
            out += [s[1] for s in stubs]
    return out


def enum_members(t, cls, taken):
    fq = t["name"]
    consts = [c for c in t.get("constants", [])]
    lines = ["  << Complete enum: one static final instance per constant (so identity",
             "     and == hold for values / valueOf / the constants), with the",
             "     java.lang.Enum behavior. Obtain the type handle as",
             f"     new {cls}(null, -1) and call values() / valueOf(name) on it. >>"]
    for i, c in enumerate(consts):
        if usable(c, cls) and c not in taken:
            lines.append(f'  static final {cls} {c} = new {cls}("{c}", {i});')
    lines += [
        "  String enumName;",
        "  int enumOrdinal;",
        f"  {cls}(String name, int ordinal) {{ this.enumName = name; this.enumOrdinal = ordinal; }}",
        "  String name() { return this.enumName; }",
        "  int ordinal() { return this.enumOrdinal; }",
        "  String toString() { return this.enumName; }",
        f"  int compareTo({cls} o) {{ return this.enumOrdinal - o.enumOrdinal; }}",
        "  boolean equals(Any other) { return this == other; }",
        "  int hashCode() { return this.enumOrdinal * 31 + 17; }",
        f"  {cls}[] values() {{",
        f"    {cls}[] v = new {cls}[{len(consts)}];",
    ]
    for i, c in enumerate(consts):
        if usable(c, cls) and c not in taken:
            lines.append(f"    v[{i}] = {c};")
    lines += ["    return v;", "  }",
              f"  {cls} valueOf(String name) {{",
              '    if (name == null) { throw new NullPointerException("Name is null"); }']
    for c in consts:
        if usable(c, cls) and c not in taken:
            lines.append(f'    if (name == "{c}") {{ return {c}; }}')
    lines += [f'    throw new IllegalArgumentException("No enum constant {fq}." + name);', "  }"]
    return lines


def record_members(t, cls, taken):
    comps = t.get("components", [])
    params = ", ".join(f"{sl_type(ty)} {n}" for n, ty in comps)
    assigns = " ".join(f"this.{n} = {n};" for n, ty in comps)
    lines = ["  << Complete record: canonical constructor, accessors, and the Java record",
             "     equals / hashCode / toString contracts over the components. >>"]
    for n, ty in comps:
        lines.append(f"  {sl_type(ty)} {n};")
    lines.append(f"  {cls}({params}) {{ {assigns} }}")
    for n, ty in comps:
        lines.append(f"  {sl_type(ty)} {n}() {{ return this.{n}; }}")
    parts = ' + ", " + '.join(f'"{n}=" + this.{n}' for n, ty in comps) or '""'
    lines.append(f'  String toString() {{ return "{cls}[" + {parts} + "]"; }}')
    eqs = " && ".join(f"o.{n}() == this.{n}" for n, ty in comps) or "true"
    lines.append(f"  boolean equals(Any other) {{ if (other instanceof {cls}) {{ {cls} o = ({cls}) other; return {eqs}; }} return false; }}")
    lines.append("  int hashCode() {")
    lines.append("    long h = 0;")
    for n, ty in comps:
        lines.append(f'    h = (h * 31 + javaStringHashCode(javaStringFromUtf8("" + this.{n}))) % 4294967296;')
    lines.append("    if (h > 2147483647) { h = h - 4294967296; }")
    lines.append("    return (int) h;")
    lines.append("  }")
    return lines


def process(t, check: bool, stats):
    path = type_file(t["name"], t["binary"])
    created = False
    if not path.is_file():
        src = new_file_text(t)
        created = True
    else:
        src = path.read_text(encoding="utf-8", errors="replace")
    mo = re.search(r"^class (\w+)(?: extends \w+)? \{$", src, re.M)
    if not mo:
        stats["skipped"] += 1
        return False
    cls = mo.group(1)
    base = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n", "", src, flags=re.S)
    has_impl = IMPL_BEGIN in base
    fields = set(FIELD_DECL.findall(base))
    methods = set(METHOD_DECL.findall(base))
    # instance fields in the class body (top-level members, not static)
    inst = len([1 for m in re.finditer(r"^  (?!static)[A-Za-z_][\w\[\]]* +\w+\s*(?:=|;)", base, re.M)])
    decl = declarations(t, cls, fields, methods, inst, has_impl)
    new = base
    if decl:
        block = BEGIN + "\n" + "\n".join(decl) + "\n" + END + "\n"
        sig = "  < ---- BEGIN java signatures"
        if sig in base:
            # keep the declarations ahead of the transcribed signature stubs
            i = base.index(sig)
            new = base[:i].rstrip("\n") + "\n\n" + block + "\n" + base[i:]
        else:
            b = base.rstrip()
            new = b[:-1].rstrip("\n") + "\n\n" + block + "}\n"
        new = re.sub(r"^#sleela \d+\.\d+$", "#sleela 3.0", new, count=1, flags=re.M)
    if new != src or created:
        stats["created" if created else "changed"] += 1
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(new, encoding="utf-8")
        return True
    return False


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    types = [json.loads(l) for l in API.read_text(encoding="utf-8").splitlines() if l.strip()]
    stats = {"created": 0, "changed": 0, "skipped": 0}
    for t in types:
        process(t, args.check, stats)
    print(f"declarations: {len(types)} types; files created {stats['created']}, updated {stats['changed']}, skipped {stats['skipped']}")
    return 1 if args.check and (stats["created"] or stats["changed"]) else 0


if __name__ == "__main__":
    sys.exit(main())
