const http80_crypto_algorithm *http80_crypto_find(const char *name){ size_t n=http80_crypto_catalog(NULL); if(!name)return NULL; for(size_t i=0;i<n;i++)if(strcmp(catalog[i].name,name)==0)return &catalog[i]; return NULL; }
int http80_crypto_is_approved(const char *name){ const http80_crypto_algorithm *a=http80_crypto_find(name); return a&&a->approved_for_new_sessions; }
int http80_crypto_select(const char *name,http80_crypto_selection *s){ if(!s||!name)return 0; memset(s,0,sizeof(*s)); s->algorithm=name; const http80_crypto_algorithm *a=http80_crypto_find(name); if(!a){snprintf(s->reason,sizeof(s->reason),"unknown algorithm");return 0;} s->available=1; s->approved=a->approved_for_new_sessions; s->provider="backend/provider"; snprintf(s->reason,sizeof(s->reason),a->approved_for_new_sessions?"catalogued; provider must verify availability":"legacy/restricted; explicit policy required"); return 1; }
