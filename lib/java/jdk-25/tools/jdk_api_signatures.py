#!/usr/bin/env python3
"""Write the exact Java method signatures of the JDK API into /lib/java.

Source of truth: lib/java/api/jdk-signatures.jsonl, written by
tools/ApiSignatures.java from a real JDK. Modifiers, type parameters,
generic return/parameter types (fully qualified), varargs and throws come
from reflection; parameter names are the ones written in the JDK source
(declarations only, read with the javac parser).

For every public type, each public/protected method that SLeeLa does not
implement yet is written, exactly as Java declares it, into

    < ---- BEGIN java signatures (generated by tools/jdk_api_signatures.py) ---- >
    ...
    < ---- END java signatures ---- >

e.g.  public <T> T[] toArray(T[] a) { throw new UnsupportedOperationException(...); }
      public static <T> java.util.List<T> asList(T... a) { ... }
      public abstract E get(int index) { throw new AbstractMethodError(...); }

The SLeeLa front end (syntax 3.0) reads this Java surface: char/byte/short
ride the int slot and float the double slot, type variables and
package-qualified reference types erase to Any (java.lang.String to String),
T... is an array parameter, and static members are called through the class
name (Math.abs(x), Integer.MAX_VALUE).

Bodies: an abstract method throws java.lang.AbstractMethodError (what the
JVM does for a missing implementation); any other method throws
UnsupportedOperationException naming the Java signature until its SLeeLa
logic is written.

Two adaptations remain, both named in the source:
  * a Java *protected instance* member carries @JavaProtected instead of the
    keyword, because SLeeLa reserves `protected` for static members (its
    degree-2 safety rule);
  * a parameter whose Java name is a SLeeLa reserved word gets a trailing _.

A Java overload is NOT written when an implemented method of the type (or
of a SLeeLa ancestor with an implementation block) with the same name and
number of parameters already accepts its arguments -- a stub must never take
a call away from working behavior, and under overload resolution an exact
match beats an assignable one. Acceptance compares the kinds the VM can tell
apart: int, long, short, byte and char share one integer kind, float and
double one floating kind, then boolean, String, arrays, and references; an
implemented parameter declared Any, Object or a type variable accepts
anything, one declared with a class type accepts any reference, and a
floating parameter accepts an integer. Envelope helpers outside the implementation
block (available, invoke, ...) and fields still block by name. A stub is also
skipped when an earlier overload erases to the same SLeeLa signature. Constructors are written into a
separate "java constructors" block (overload resolution, SLEELA.syntax section 40),
skipping any arity the type already declares.
java.lang.String is left for the String bridge.

Idempotent; run it last (after the implementation generators and
jdk_api_declare.py). usage: python3 lib/java/tools/jdk_api_signatures.py [--check]
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import jdk_api_declare as dec  # noqa: E402

ROOT = dec.ROOT
SIGS = ROOT / "api" / "jdk-signatures.jsonl"
BEGIN = "  < ---- BEGIN java signatures (generated by tools/jdk_api_signatures.py) ---- >"
END = "  < ---- END java signatures ---- >"
CBEGIN = "  < ---- BEGIN java constructors (generated by tools/jdk_api_signatures.py) ---- >"
CEND = "  < ---- END java constructors ---- >"
IMPL = re.compile(r"< ---- BEGIN java implementation.*?---- >\n(.*?)  < ---- END java implementation ---- >", re.S)
METHOD = re.compile(r"^  (?:@\w+\s+)?(?:(?:public|protected|private|static|final|abstract|default|synchronized|native|strictfp) )*(?:<[^()]*> )?[A-Za-z_][\w.]*(?:<[^()]*>)?(?:\[\])* +(\w+)\s*\(", re.M)
SKIP_TYPES = {"java.lang.String"}
RESERVED_PARAMS = dec.RESERVED | {"next"}


def erased(t: str, tvars: set) -> str:
    """The SLeeLa type the front end gives a Java type (for overload dedupe)."""
    if t.endswith("..."):
        t = t[:-3] + "[]"
    dims = ""
    while t.endswith("[]"):
        dims += "[]"
        t = t[:-2]
    raw = t.split("<", 1)[0]
    if raw in tvars:
        return "Any" + dims
    if "." in raw and raw[:1].islower():
        return ("String" if raw == "java.lang.String" else "Any") + dims
    return raw + dims


def tvar_names(tparams: str) -> set:
    if not tparams:
        return set()
    inner, depth, cur, out = tparams[1:-1], 0, "", []
    for ch in inner:
        if ch == "<":
            depth += 1
        elif ch == ">":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    out.append(cur)
    return {x.strip().split(" ", 1)[0] for x in out if x.strip()}


def render(type_name: str, m: dict) -> str:
    mods = m["mods"].split()
    lines = []
    if m["protected"] and not m["static"]:
        mods = [x for x in mods if x != "protected"]
        lines.append("  @JavaProtected")
    params = []
    for ptype, pname in m["params"]:
        if pname in RESERVED_PARAMS:
            pname = pname + "_"
        params.append(f"{ptype} {pname}")
    head = " ".join(mods + ([m["tparams"]] if m["tparams"] else []) + [m["ret"], m["name"]])
    throws = (" throws " + ", ".join(m["throws"])) if m["throws"] else ""
    jsig = type_name + "." + m["name"] + "(" + ", ".join(p[0] for p in m["params"]) + ")"
    jsig = jsig.replace('"', "'")
    if m["abstract"]:
        body = f'throw new AbstractMethodError("{jsig}");'
    else:
        body = f'throw new UnsupportedOperationException("not yet implemented in SLeeLa: {jsig}");'
    lines.append(f"  {head}({', '.join(params)}){throws} {{ {body} }}")
    return "\n".join(lines)


def split_top(s: str) -> list:
    """Split a parameter list on top-level commas (generics keep their commas)."""
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch in "<(":
            depth += 1
        elif ch in ">)":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur)
    return out


def render_ctor(type_name: str, cls: str, m: dict) -> str:
    mods = [x for x in m["mods"].split() if x in ("public", "protected")]
    lines = []
    if m["protected"]:
        mods = [x for x in mods if x != "protected"]
        lines.append("  @JavaProtected")
    params = []
    for ptype, pname in m["params"]:
        if pname in RESERVED_PARAMS:
            pname = pname + "_"
        params.append(f"{ptype} {pname}")
    head = " ".join(mods + [cls])
    throws = (" throws " + ", ".join(m["throws"])) if m["throws"] else ""
    jsig = type_name + ".<init>(" + ", ".join(p[0] for p in m["params"]) + ")"
    jsig = jsig.replace('"', "'")
    body = f'throw new UnsupportedOperationException("not yet implemented in SLeeLa: {jsig}");'
    lines.append(f"  {head}({', '.join(params)}){throws} {{ {body} }}")
    return "\n".join(lines)


IMPL_SIG = re.compile(r"^  (?:@\w+\s+)?(?:(?:public|protected|private|static|final|abstract|default|synchronized|native|strictfp) )*(?:<[^()]*> )?[A-Za-z_][\w.]*(?:<[^()]*>)?(?:\[\])* +(\w+)\s*\(([^)]*)\)", re.M)
INT_KIND = {"int", "long", "short", "byte", "char"}
FLOAT_KIND = {"float", "double"}


def kind(t: str, tvars: set) -> str:
    """The parameter kind the VM tells apart (see the module docstring)."""
    t = t.strip()
    if t.startswith("final "):
        t = t[6:].strip()
    if t.endswith("..."):
        t = t[:-3] + "[]"
    if t.endswith("[]"):
        return "[" + kind(t[:-2], tvars)
    raw = t.split("<", 1)[0].strip()
    if raw in INT_KIND:
        return "I"
    if raw in FLOAT_KIND:
        return "D"
    if raw == "boolean":
        return "Z"
    if raw in ("String", "string", "java.lang.String"):
        return "S"
    if raw in ("Any", "Object", "java.lang.Object") or raw in tvars or (len(raw) == 1 and raw.isupper()):
        return "A"
    return "R"


def param_types(params: str) -> list:
    out = []
    for p in split_top(params):
        p = p.strip()
        if not p:
            continue
        out.append(p.rsplit(" ", 1)[0] if " " in p else p)
    return out


def impl_sigs(text: str) -> dict:
    """name -> list of parameter-kind tuples of the methods declared in text."""
    out = {}
    for name, params in IMPL_SIG.findall(text):
        out.setdefault(name, []).append(tuple(kind(t, set()) for t in param_types(params)))
    return out


def accepts(impl_kinds: tuple, java_kinds: tuple) -> bool:
    if len(impl_kinds) != len(java_kinds):
        return False
    for have, want in zip(impl_kinds, java_kinds):
        if have == want or have == "A":
            continue
        if have == "R" and want == "A":
            continue
        if have == "D" and want == "I":
            continue
        return False
    return True


def renderable_text(text: str) -> bool:
    return "@" not in text and "$" not in text


def renderable(m: dict) -> bool:
    text = " ".join([m["ret"], m["tparams"]] + [p[0] for p in m["params"]] + m["throws"])
    # annotation-typed or otherwise exotic spellings the front end does not read
    return "@" not in text and "$" not in text


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    sigs = {json.loads(l)["name"]: json.loads(l) for l in SIGS.read_text(encoding="utf-8").splitlines() if l.strip()}
    api = {json.loads(l)["name"]: json.loads(l) for l in dec.API.read_text(encoding="utf-8").splitlines() if l.strip()}

    texts, impl_names = {}, {}
    for name, t in api.items():
        p = dec.type_file(t["name"], t["binary"])
        if p.is_file():
            src = p.read_text(encoding="utf-8", errors="replace")
            texts[name] = (p, src)
            mo = IMPL.search(src)
            impl_names[name] = impl_sigs(mo.group(1)) if mo else {}

    def inherited(name):
        out, n = {}, api[name].get("super")
        for _ in range(40):
            if not n or n not in api:
                break
            for k, v in impl_names.get(n, {}).items():
                out.setdefault(k, []).extend(v)
            n = api[n].get("super")
        return out

    changed = total = abstract = ctors = 0
    for name, t in api.items():
        if name not in texts or name in SKIP_TYPES or name not in sigs:
            continue
        path, src = texts[name]
        mo = re.search(r"^class (\w+)(<[^{}]*>)?(?: extends \w+)? \{$", src, re.M)
        if not mo:
            continue
        cls = mo.group(1)
        base = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n", "", src, flags=re.S)
        base = re.sub(re.escape(CBEGIN) + r".*?" + re.escape(CEND) + r"\n", "", base, flags=re.S)
        # The class header carries the Java type parameters (class HashMap<K, V>).
        tps = sigs[name]["tparams"] if name in sigs else ""
        if tps and not mo.group(2) and renderable_text(tps):
            hdr = mo.group(0)
            base = base.replace(hdr, hdr.replace("class " + cls, "class " + cls + tps, 1), 1)
        mo_impl = IMPL.search(base)
        outside = IMPL.sub("", base) if mo_impl else base
        blocked = set(METHOD.findall(outside)) | set(dec.FIELD_DECL.findall(base))
        own = impl_sigs(mo_impl.group(1)) if mo_impl else {}
        for k, v in inherited(name).items():
            own.setdefault(k, []).extend(v)

        def taken(m, tv):
            want = tuple(kind(p[0], tv) for p in m["params"])
            return any(accepts(have, want) for have in own.get(m["name"], []))
        class_tvars = tvar_names(sigs[name]["tparams"])
        seen, lines = set(), []
        for m in sigs[name]["members"]:
            if m["name"] == "<init>" or m["name"] in blocked or not dec.usable(m["name"], cls) or not renderable(m):
                continue
            tv = class_tvars | tvar_names(m["tparams"])
            if taken(m, tv):
                continue
            key = (m["name"], tuple(erased(p[0], tv) for p in m["params"]))
            if key in seen:
                continue
            seen.add(key)
            lines.append(render(name, m))
            total += 1
            abstract += 1 if m["abstract"] else 0
        # Constructors: overload resolution binds by arity then type, so each Java
        # constructor is written unless the type already declares one of that arity.
        have = {len(split_top(x)) for x in re.findall(r"^  (?:@\w+\s+)?(?:public|protected|private)? ?" + re.escape(cls) + r"\s*\(([^)]*)\)", base, re.M)}
        ctor_lines, cseen = [], set()
        for m in sigs[name]["members"]:
            if m["name"] != "<init>" or m["tparams"] or not renderable(m) or len(m["params"]) in have:
                continue
            tv = class_tvars | tvar_names(m["tparams"])
            ckey = tuple(erased(p[0], tv) for p in m["params"])
            if ckey in cseen:
                continue
            cseen.add(ckey)
            ctor_lines.append(render_ctor(name, cls, m))
            ctors += 1
        new = base
        if lines or ctor_lines:
            block = ""
            if lines:
                block += (BEGIN + "\n  << Exact Java signatures (from the JDK). A method body that is not yet\n"
                          "     SLeeLa logic throws: AbstractMethodError for an abstract method, else\n"
                          "     UnsupportedOperationException naming the Java signature. >>\n"
                          + "\n".join(lines) + "\n" + END + "\n")
            if ctor_lines:
                block += ("\n" if block else "") + (CBEGIN + "\n  << Exact Java constructor signatures (from the JDK). Overload resolution binds a\n"
                          "     call by arity, then best type match. Each body throws\n"
                          "     UnsupportedOperationException until its SLeeLa logic is written. >>\n"
                          + "\n".join(ctor_lines) + "\n" + CEND + "\n")
            b = base.rstrip()
            new = b[:-1].rstrip("\n") + "\n\n" + block + "}\n"
            new = re.sub(r"^#sleela \d+\.\d+$", "#sleela 3.0", new, count=1, flags=re.M)
        if new != src:
            changed += 1
            if not args.check:
                path.write_text(new, encoding="utf-8")
    print(f"signatures: {total} exact Java method signatures, {ctors} constructors ({abstract} abstract, {total - abstract} awaiting logic); "
          f"files {'to update' if args.check else 'updated'}: {changed}")
    return 1 if args.check and changed else 0


if __name__ == "__main__":
    sys.exit(main())
