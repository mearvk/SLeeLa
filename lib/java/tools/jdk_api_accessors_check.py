#!/usr/bin/env python3
"""Run-time check of the probed accessor contracts in SLeeLa.

For every class implemented by jdk_api_accessors.py, writes a SLeeLa program
(one per Java package) that constructs the class with distinct arguments and
asserts each observed contract: the getter returns the constructor argument,
the initial-state value, and the setter / getter round trip. Runs each
program with the SLeeLa VM and reports PASS / FAIL per package.

usage: python3 lib/java/tools/jdk_api_accessors_check.py [path/to/sleela]
"""
from __future__ import annotations

import collections
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import jdk_api_declare as dec  # noqa: E402
import jdk_api_accessors as acc  # noqa: E402
import jdk_api_signatures as sg  # noqa: E402

REPO = dec.ROOT.parents[1]


def value(sl_t: str, i: int) -> str:
    return {"int": str(11 + i * 37), "long": str((11 + i * 37) * 1000003), "double": f"{11 + i * 37}.5",
            "boolean": "true" if i % 2 == 0 else "false", "String": f'"s{i}"'}.get(sl_t, str(900 + i))


def main() -> int:
    sleela = sys.argv[1] if len(sys.argv) > 1 else str(REPO / "impl" / "build" / "sleela")
    sigs = {json.loads(l)["name"]: json.loads(l) for l in sg.SIGS.read_text().splitlines() if l.strip()}
    api = {json.loads(l)["name"]: json.loads(l) for l in dec.API.read_text().splitlines() if l.strip()}
    by_pkg = collections.defaultdict(list)
    grouped = {}
    for line in acc.ACC.read_text().splitlines():
        if line.strip():
            x = json.loads(line)
            grouped.setdefault(x["name"], []).append(x)
    # the primary (first written) constructor is the probe line with the most observations
    for e in [x for v in grouped.values() for x in v]:
        t = api.get(e["name"])
        if t is None or "$" in t["binary"]:
            continue  # nested types are not resolved by the loader yet
        path = dec.type_file(t["name"], t["binary"])
        src = path.read_text(errors="replace") if path.is_file() else ""
        if "accessor contract (generated by tools/jdk_api_accessors.py)" not in src:
            continue
        cls = t["binary"].rsplit(".", 1)[1]
        params = None
        for m in re.finditer(r"  public " + cls + r"\(([^)]*)\)", src):
            ps = [p.strip() for p in re.split(r",(?![^<]*>)", m.group(1)) if p.strip()]
            if [acc.raw(p.rsplit(" ", 1)[0]) for p in ps] == [acc.raw(x) for x in e["ctor"]]:
                params = ps
                break
        if params is None:
            continue  # this probed constructor was not written
        args = []
        for i, p in enumerate(params):
            ptype = p.rsplit(" ", 1)[0]
            args.append("null" if acc.raw(ptype).endswith("[]") else value(dec.sl_type(acc.raw(ptype)), i))
        checks = []
        v = f"x{len(by_pkg[t['binary'].rsplit('.', 1)[0]])}"
        lines = [f"    {cls} {v} = new {cls}({', '.join(args)});"]
        ctor = next((k for k in sigs[t["name"]]["members"] if k["name"] == "<init>" and [acc.raw(q[0]) for q in k["params"]] == [acc.raw(x) for x in e["ctor"]]), None)
        for kind, a, b in e["obs"]:
            if not re.search(r"\s" + re.escape(a) + r"\(", src.split("BEGIN java implementation", 1)[-1].split("END java implementation", 1)[0]):
                continue
            if kind == "param":
                lines.append(f'    if ({v}.{a}() != {args[b]}) {{ bad = bad + 1; print("FAIL {t["name"]}.{a}() param"); }}')
            elif kind == "constant":
                g = next((k for k in sigs[t["name"]]["members"] if k["name"] == a and not k["params"]), None)
                lit = acc.literal(dec.sl_type(acc.raw(g["ret"])), b) if g else None
                if lit is not None:
                    lines.append(f'    if ({v}.{a}() != {lit}) {{ bad = bad + 1; print("FAIL {t["name"]}.{a}() initial"); }}')
            elif kind == "setter":
                g = next((k for k in sigs[t["name"]]["members"] if k["name"] == b and not k["params"]), None)
                if g:
                    val = value(dec.sl_type(acc.raw(g["ret"])), 5)
                    lines.append(f"    {v}.{a}({val});")
                    lines.append(f'    if ({v}.{b}() != {val}) {{ bad = bad + 1; print("FAIL {t["name"]}.{a} / {b} round trip"); }}')
        by_pkg[t["binary"].rsplit(".", 1)[0]].append("\n".join(lines))
    tmp = Path(tempfile.mkdtemp(prefix="sleela-accessors-"))
    env = dict(os.environ, SLEELA_HOME=str(REPO), SLEELA_LIB=str(REPO / "lib"))
    failed = total = 0
    for pkg, blocks in sorted(by_pkg.items()):
        name = "Acc" + re.sub(r"\W", "", pkg.title())
        src = (f"#sleela 3.0\nmaterial;\nimport java.{pkg};\nclass {name} {{\n  int bad = 0;\n  void main() {{\n"
               + "\n".join(blocks) + f'\n    print("{pkg} failures=" + bad);\n  }}\n}}\n')
        f = tmp / f"{name}.sleela"
        f.write_text(src)
        r = subprocess.run([sleela, "run", f.name], cwd=tmp, env=env, capture_output=True, text=True, timeout=600)
        out = [l for l in (r.stdout + r.stderr).splitlines() if not re.search(r"memory-manager|^verification|\[security\]|\[defender\]", l)]
        total += len(blocks)
        last = out[-1] if out else ""
        if not last.endswith("failures=0"):
            failed += 1
            print(f"FAIL  {pkg}: " + " | ".join(out[-3:])[:400])
    print(f"accessor check: {len(by_pkg)} packages, {total} classes, {failed} packages failing")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
