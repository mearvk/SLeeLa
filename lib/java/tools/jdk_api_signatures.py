#!/usr/bin/env python3
"""Transcribe the remaining JDK method signatures into /lib/java as stubs.

For every public type in lib/java/api/jdk-api.jsonl, each public/protected
method that SLeeLa does not have yet is written into a signatures block

    < ---- BEGIN java signatures (generated by tools/jdk_api_signatures.py) ---- >
    ...
    < ---- END java signatures ---- >

with its Java name and its parameters and return type mapped to the types
SLeeLa supports (the mapping of jdk_api_declare.py: int/short/byte/char ->
int, long -> long, float/double -> double, boolean, String, primitive arrays,
other references -> Any). Each stub throws UnsupportedOperationException
naming the exact Java signature, so the logic can be filled in method by
method; until then a call fails loudly instead of silently.

A method is NOT transcribed when:
  * the type (or any SLeeLa ancestor with an implementation block) already
    declares a method of that name -- a stub must never shadow working,
    inherited behavior, and calls still resolve by name only;
  * its name is a SLeeLa reserved word or an envelope helper;
  * it is abstract (jdk_api_declare.py declares those);
  * an earlier overload erases to the same SLeeLa signature.
java.lang.String is skipped (see SKIP_TYPES). Constructors are not transcribed: a class admits one constructor, and a
throwing constructor would break existing `new` uses of the envelopes.

Signature stubs are not counted as coverage by jdk_api_coverage.py; it
reports them separately.

Idempotent. usage: python3 lib/java/tools/jdk_api_signatures.py [--check]
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import jdk_api_declare as dec  # noqa: E402

ROOT = dec.ROOT
BEGIN = "  < ---- BEGIN java signatures (generated by tools/jdk_api_signatures.py) ---- >"
END = "  < ---- END java signatures ---- >"
IMPL = re.compile(r"< ---- BEGIN java implementation.*?---- >\n(.*?)  < ---- END java implementation ---- >", re.S)
# return types may carry generic arguments in hand-written sources (Class<?>)
METHOD = re.compile(r"^  (?:public |protected |private |static |final )*[A-Za-z_][\w.]*(?:<[^()]*>)?(?:\[\])* +(\w+)\s*\(", re.M)


# java.lang.String is loaded by every program that names the built-in String
# type, and its stubs could never be reached (String values are VM strings),
# so it is left for the String bridge rather than transcribed.
SKIP_TYPES = {"java.lang.String"}


def short(t: str) -> str:
    return t.rsplit(".", 1)[-1]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    types = {json.loads(l)["name"]: json.loads(l) for l in dec.API.read_text(encoding="utf-8").splitlines() if l.strip()}

    texts, impl_names = {}, {}
    for name, t in types.items():
        p = dec.type_file(t["name"], t["binary"])
        if p.is_file():
            src = p.read_text(encoding="utf-8", errors="replace")
            texts[name] = (p, src)
            m = IMPL.search(src)
            impl_names[name] = set(METHOD.findall(m.group(1))) if m else set()

    def inherited(name):
        """Method names implemented by SLeeLa ancestors of a type."""
        out = set()
        n = types[name].get("super")
        for _ in range(40):
            if not n or n not in types:
                break
            out |= impl_names.get(n, set())
            n = types[n].get("super")
        return out

    changed = stubs_total = 0
    for name, t in types.items():
        if name not in texts:
            continue
        if name in SKIP_TYPES:
            continue
        path, src = texts[name]
        mo = re.search(r"^class (\w+)(?: extends \w+)? \{$", src, re.M)
        if not mo:
            continue
        cls = mo.group(1)
        base = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n", "", src, flags=re.S)
        present = set(METHOD.findall(base)) | set(dec.FIELD_DECL.findall(base))
        blocked = present | inherited(name)
        seen, lines = set(), []
        for m in t["methods"]:
            mname, ret, params, is_static, is_abstract = m[0], m[1], m[2], m[3], m[4]
            if mname == "<init>" or is_abstract or mname in blocked or not dec.usable(mname, cls):
                continue
            key = (mname, tuple(dec.sl_type(p) for p in params))
            if key in seen:
                continue
            seen.add(key)
            ps = ", ".join(f"{dec.sl_type(p)} p{i}" for i, p in enumerate(params))
            jsig = ("static " if is_static else "") + f"{short(ret)} {name}.{mname}(" + ", ".join(short(p) for p in params) + ")"
            lines.append(f'  {dec.sl_type(ret)} {mname}({ps}) {{ throw new UnsupportedOperationException("not yet implemented in SLeeLa: {jsig}"); }}')
        new = base
        if lines:
            stubs_total += len(lines)
            block = (BEGIN + "\n  << Transcribed Java signatures awaiting their SLeeLa logic (static methods\n"
                     "     are instance methods, as everywhere in lib/java). Each stub throws\n"
                     "     UnsupportedOperationException naming the Java signature. >>\n"
                     + "\n".join(lines) + "\n" + END + "\n")
            b = base.rstrip()
            new = b[:-1].rstrip("\n") + "\n\n" + block + "}\n"
            new = re.sub(r"^#sleela \d+\.\d+$", "#sleela 3.0", new, count=1, flags=re.M)
        if new != src:
            changed += 1
            if not args.check:
                path.write_text(new, encoding="utf-8")
    print(f"signatures: {stubs_total} method stubs in {len(texts)} types; files {'to update' if args.check else 'updated'}: {changed}")
    return 1 if args.check and changed else 0


if __name__ == "__main__":
    sys.exit(main())
